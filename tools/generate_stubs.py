"""
Generate the type stubs (.pyi) of the query and aggregation types

PyCharm doesn't check a type inside itself (recursion), e.g. the clauses of a bool query (which are queries too)
would not be checked. So in the stubs every level of nesting has its own copy of the recursive types, the last level
is recursive. The copies have the same keys, so they are compatible with each other.

The stubs are generated from the source modules, don't edit them. Run it after the query or aggregation types are
changed: ``python tools/generate_stubs.py``. With ``--check`` it only checks that the stubs are up to date.
"""
from typing import Dict, List, Set

import ast
import copy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / 'esorm'

HEADER = '''"""
GENERATED FILE, DON'T EDIT: it is generated by tools/generate_stubs.py from {source}

See the docstring of tools/generate_stubs.py for details.
"""
'''


class Module:
    """
    A module whose recursive types are copied for every level of nesting

    :param name: The module name
    :param top: The top level type (e.g. ESQuery)
    :param level_alias: The alias of the top level type, which is used for the 1st level of nesting
                        (e.g. ESQueryClause), it is the name of the 1st level copy in the stub
    :param levels: The number of levels of nesting which have their own copies
    :param copied: The other types which have their own copies on every level (they use the level alias), the
                   others are shared by the levels, so PyCharm doesn't check the clauses under them. Only the most
                   often nested types are copied, and only on a few levels: pyright compares the copies structurally
                   (e.g. when an ESQuery is used as a clause), it gets exponentially slow with more copies and levels,
                   and PyCharm gets slow too.
    :param runtime_only: Names of the module level functions which are left out of the stub
    """

    def __init__(self, name: str, top: str, level_alias: str, levels: int, copied: Set[str] = frozenset(),
                 runtime_only: Set[str] = frozenset()):
        self.name = name
        self.top = top
        self.level_alias = level_alias
        self.levels = levels
        self.copied = copied
        self.runtime_only = runtime_only


MODULES = [
    Module('query', top='ESQuery', level_alias='ESQueryClause', levels=2, copied={'ESBool', 'ESClauses'},
           runtime_only={'_sequence_not_str_schema'}),
    Module('aggs', top='ESAgg', level_alias='ESSubAgg', levels=2),
]


def _names(node: ast.AST) -> Set[str]:
    """ The names used in an annotation, including forward references (strings) """
    res = set()
    for n in ast.walk(node):
        if isinstance(n, ast.Name):
            res.add(n.id)
        elif isinstance(n, ast.Constant) and isinstance(n.value, str) and n.value.isidentifier():
            res.add(n.value)
    return res


def _is_literal(node: ast.Subscript) -> bool:
    """ The strings in Literal[...] are values, not forward references """
    value = node.value
    return (isinstance(value, ast.Name) and value.id == 'Literal') or \
        (isinstance(value, ast.Attribute) and value.attr == 'Literal')


class _Rename(ast.NodeTransformer):
    """ Rename names (and forward references) in annotations """

    def __init__(self, mapping: Dict[str, str]):
        self.mapping = mapping

    def visit_Name(self, node: ast.Name) -> ast.AST:
        if node.id in self.mapping:
            return ast.copy_location(ast.Name(id=self.mapping[node.id], ctx=node.ctx), node)
        return node

    def visit_Constant(self, node: ast.Constant) -> ast.AST:
        if isinstance(node.value, str) and node.value in self.mapping:
            return ast.copy_location(ast.Constant(value=self.mapping[node.value]), node)
        return node

    def visit_Subscript(self, node: ast.Subscript) -> ast.AST:
        return node if _is_literal(node) else self.generic_visit(node)


class _Unquote(ast.NodeTransformer):
    """
    Forward references (strings) to names: they are not needed in stubs, and PyCharm doesn't resolve them in some
    places (e.g. ``Required['ESQueryClause']``)
    """

    def visit_Constant(self, node: ast.Constant) -> ast.AST:
        if isinstance(node.value, str) and node.value.isidentifier():
            return ast.copy_location(ast.Name(id=node.value, ctx=ast.Load()), node)
        return node

    def visit_Subscript(self, node: ast.Subscript) -> ast.AST:
        return node if _is_literal(node) else self.generic_visit(node)


def _unquote_annotations(tree: ast.AST) -> None:
    """ Replace the forward references in all annotations and type aliases """
    for node in ast.walk(tree):
        if isinstance(node, ast.AnnAssign):
            node.annotation = _Unquote().visit(node.annotation)
            if isinstance(node.annotation, ast.Name) and node.annotation.id == 'TypeAlias' and node.value:
                node.value = _Unquote().visit(node.value)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for arg in node.args.args + node.args.kwonlyargs + node.args.posonlyargs:
                if arg.annotation:
                    arg.annotation = _Unquote().visit(arg.annotation)
            if node.returns:
                node.returns = _Unquote().visit(node.returns)


def _rename_class(cls: ast.ClassDef, name: str, mapping: Dict[str, str], doc: str) -> ast.ClassDef:
    """ Copy a TypedDict class with a new name, renaming the names in its annotations and bases """
    new = copy.deepcopy(cls)
    new.name = name
    renamer = _Rename(mapping)
    new.bases = [renamer.visit(b) for b in new.bases]
    body: List[ast.stmt] = [ast.Expr(ast.Constant(doc))]
    for i, stmt in enumerate(new.body):
        if i == 0 and isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant):
            continue  # The docstring of the class is replaced
        if isinstance(stmt, ast.AnnAssign):
            stmt.annotation = renamer.visit(stmt.annotation)
        body.append(stmt)
    new.body = body
    return new


def _strip_function(func: ast.FunctionDef) -> ast.FunctionDef:
    """ Stubs have only the signatures (and docstrings) """
    body: List[ast.stmt] = []
    if func.body and isinstance(func.body[0], ast.Expr) and isinstance(func.body[0].value, ast.Constant) \
            and isinstance(func.body[0].value.value, str):
        body.append(func.body[0])
    body.append(ast.Expr(ast.Constant(...)))
    func.body = body
    return func


def _is_overload(func: ast.FunctionDef) -> bool:
    return any(isinstance(d, ast.Name) and d.id == 'overload' for d in func.decorator_list)


def _strip_class(cls: ast.ClassDef) -> ast.ClassDef:
    """ Strip the method bodies, and leave out the implementations of overloaded methods """
    overloaded = {s.name for s in cls.body if isinstance(s, ast.FunctionDef) and _is_overload(s)}
    body: List[ast.stmt] = []
    for stmt in cls.body:
        if isinstance(stmt, ast.FunctionDef):
            if stmt.name in overloaded and not _is_overload(stmt):
                continue
            stmt = _strip_function(stmt)
        body.append(stmt)
    cls.body = body
    return cls


def generate(module: Module) -> str:
    """ Generate the stub of a module """
    source_file = PACKAGE / f'{module.name}.py'
    tree = ast.parse(source_file.read_text())
    classes = {n.name: n for n in tree.body if isinstance(n, ast.ClassDef)}
    aliases = {n.target.id: n for n in tree.body if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)}

    assert module.top in classes, f"{module.top} is not a class in {source_file}"
    family = {module.top} | set(module.copied)
    for name in module.copied:
        assert name in classes or name in aliases, f"{name} is not a class or type alias in {source_file}"

    def level_name(name: str, level: int) -> str:
        if name == module.top:
            return module.level_alias if level == 1 else f'_{module.level_alias}_L{level}'
        return f'_{name.lstrip("_")}_L{level}'

    def level_mapping(level: int) -> Dict[str, str]:
        # The types of a level use the clause of the next level, the last level is recursive
        mapping = {name: level_name(name, level) for name in family if name != module.top}
        mapping[module.top] = level_name(module.top, level)
        mapping[module.level_alias] = level_name(module.top, min(level + 1, module.levels))
        return mapping

    body: List[ast.stmt] = []
    for node in tree.body:
        # Runtime only code
        if isinstance(node, ast.FunctionDef) and node.name in module.runtime_only:
            continue
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call) \
                and isinstance(node.value.func, ast.Name) and node.value.func.id == 'setattr':
            continue
        # The level alias is replaced by the copies of every level
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) \
                and node.target.id == module.level_alias:
            for level in range(1, module.levels + 1):
                mapping = level_mapping(level)
                for name in sorted(family, key=lambda n: tree.body.index(classes[n]) if n in classes else -1):
                    if name in classes:
                        doc = (f"Level {level} copy of {name}, see :data:`{module.level_alias}`"
                               if name != module.top else
                               f"Level {level} copy of {module.top}: a query clause, see :data:`{module.level_alias}`")
                        body.append(_rename_class(classes[name], mapping[name], mapping, doc))
                    else:
                        alias = copy.deepcopy(aliases[name])
                        alias.target = ast.Name(id=mapping[name], ctx=ast.Store())
                        alias.value = _Rename(mapping).visit(alias.value)
                        body.append(alias)
            continue
        if isinstance(node, ast.FunctionDef):
            node = _strip_function(node)
        elif isinstance(node, ast.ClassDef):
            node = _strip_class(node)
        body.append(node)

    tree.body = body
    _unquote_annotations(tree)
    ast.fix_missing_locations(tree)
    return HEADER.format(source=f'esorm/{module.name}.py') + '\n' + ast.unparse(tree) + '\n'


def main() -> int:
    check = '--check' in sys.argv[1:]
    outdated = []
    for module in MODULES:
        stub_file = PACKAGE / f'{module.name}.pyi'
        stub = generate(module)
        if check:
            if not stub_file.exists() or stub_file.read_text() != stub:
                outdated.append(str(stub_file.relative_to(ROOT)))
        else:
            stub_file.write_text(stub)
            print(f"Generated {stub_file.relative_to(ROOT)}")
    if outdated:
        print(f"The stubs are not up to date, run `python tools/generate_stubs.py`: {', '.join(outdated)}")
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
